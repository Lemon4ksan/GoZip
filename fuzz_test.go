func FuzzLoad(f *testing.F) {
	f.Add(data[:])

	f.Fuzz(func(t *testing.T, data []byte) {
		if len(data) > 10*1024*1024 {
			return
		}

		archive := NewZip()
		reader := bytes.NewReader(data)

		err := archive.Load(reader, int64(len(data)))
		if err != nil {
			return
		}

		for _, file := range archive.Files() {
			_ = file.Mode()
			_ = file.ModTime()

			rc, err := file.Open()
			if err == nil {
				buf := make([]byte, 100)
				_, _ = rc.Read(buf)
				rc.Close()
			}
		}
	})
}

func FuzzWriteRead(f *testing.F) {
	f.Add("test.txt", []byte("hello world"))
	f.Add("nested/folder/data.bin", []byte{0x00, 0x01, 0x02})
	f.Add("weird\\backslashes\\file", []byte("windows path"))

	f.Fuzz(func(t *testing.T, filename string, content []byte) {
		cleanName := strings.TrimPrefix(path.Clean(strings.ReplaceAll(filename, "\\", "/")), "/")
		if cleanName == "" || cleanName == "." || cleanName == "/" {
			return
		}

		archive := NewZip()

		err := archive.AddBytes(content, filename)
		if err != nil {
			return
		}

		buf := new(bytes.Buffer)
		_, err = archive.WriteTo(buf)
		if err != nil {
			t.Fatalf("failed to write valid archive: %v", err)
		}

		readArchive := NewZip()
		err = readArchive.Load(bytes.NewReader(buf.Bytes()), int64(buf.Len()))
		if err != nil {
			t.Fatalf("failed to load generated archive: %v", err)
		}

		fEntry, ok := readArchive.File(cleanName)
		if !ok {
			t.Fatalf("file '%s' (orig: '%s') lost after write/read cycle", cleanName, filename)
		}

		if fEntry.IsDir() {
			return
		}

		rc, err := fEntry.Open()
		if err != nil {
			t.Fatalf("failed to open entry '%s': %v", cleanName, err)
		}
		defer rc.Close()

		readContent, err := io.ReadAll(rc)
		if err != nil {
			t.Fatalf("failed to read content of '%s': %v", cleanName, err)
		}

		if !bytes.Equal(readContent, content) {
			t.Fatalf("content mismatch for '%s'.\nWrote: %d bytes\nRead:  %d bytes", cleanName, len(content), len(readContent))
		}
	})
}

func FuzzZipSlip(f *testing.F) {
	f.Add("../../../etc/passwd")
	f.Add("valid_path")
	f.Add("/absolute/path")

	f.Fuzz(func(t *testing.T, pathName string) {
		archive := NewZip()
		err := archive.AddBytes([]byte("data"), pathName)
		if err != nil {
			return
		}

		buf := new(bytes.Buffer)
		if _, err := archive.WriteTo(buf); err != nil {
			return
		}

		extractArch := NewZip()
		if err := extractArch.Load(bytes.NewReader(buf.Bytes()), int64(buf.Len())); err != nil {
			return
		}

		err = extractArch.Extract("output_dir")

		if err != nil {
			t.Logf("Got expected error for %s: %v", pathName, err)
		}
	})
}
